export interface TaxInfo {
  isTaxRelated: boolean;
  taxCategory?: string;   // free text, e.g. "80C", "Business expense"
  taxYear?: string;       // e.g. "FY 2026-27"
  deductible?: boolean;
  notes?: string;
}

export type RecurrenceFrequency = 'weekly' | 'monthly' | 'quarterly' | 'yearly';

export interface RecurringRule {
  id: string;
  type: 'expense' | 'income';
  amount: number;
  category: string;
  description: string;        // expense description OR income source
  city?: string;
  frequency: RecurrenceFrequency;
  startDate: string;          // YYYY-MM-DD
  endDate?: string;           // inclusive
  paused: boolean;
  generatedThrough?: string;  // inclusive date up to which occurrences were generated
  createdAt: string;          // ISO timestamp
  tax?: TaxInfo;
  funding?: ExpenseFunding;   // expense rules only — copied to generated transactions
}

export interface Expense {
  id: string;
  category: string;
  description: string;
  amount: number;
  date: string;
  month: string;
  year: number;
  city?: string;
  payee?: string;
  notes?: string;
  recurringId?: string; // set on transactions generated by a RecurringRule
  tax?: TaxInfo;        // per-transaction tax info; overrides the category default
  funding?: ExpenseFunding; // undefined = paid from monthly budget
}

export interface Income {
  id: string;
  source: string;
  amount: number;
  date: string;
  month: string;
  year: number;
  category?: string;   // optional — income category id
  notes?: string;
  recurringId?: string; // set on transactions generated by a RecurringRule
  tax?: TaxInfo;        // per-transaction tax info; overrides the category default
}

export interface Category {
  id: string;
  name: string;
  color: string;
  icon: string;
  type?: 'expense' | 'income' | 'both';   // undefined treated as 'expense' for backward compat
  tax?: TaxInfo; // category-level default; a transaction's own tax overrides it
  spendClass?: 'essential' | 'flexible' | 'discretionary'; // user override; undefined = auto
}

export interface SavingsGoal {
  id: string;
  name: string;
  targetAmount: number;
  savedAmount: number;
  targetDate?: string;   // YYYY-MM-DD
  archived: boolean;
  createdAt: string;     // ISO
  updatedAt: string;     // ISO
}

export interface BudgetAlertThresholds { warning: number; exceeded: number; }  // percents, defaults 80 / 100

export interface SpendingTarget {
  target: number;               // monthly amount
  baselineMonthly: number;      // category avg when the target was set
  createdAt: string;            // ISO timestamp
  createdForPeriod: string;     // 'YYYY-MM' financial period it was created in
}

export interface OpeningBalanceBaseline {
  startYear: number;        // financial year the balance starts at
  amount: number;           // may be 0 or negative (deficit — UI warns)
  effectiveDate: string;    // 'YYYY-MM-DD' — txns dated before this are ignored by balances
  createdAt: string;        // ISO timestamp
  updatedAt: string;        // ISO timestamp
}

export type FundingSource = 'budget' | 'reserve' | 'split';

/** How an expense was paid — undefined means budget (backwards compatible). */
export interface ExpenseFunding {
  source: FundingSource;
  /** only for 'split': 0 < reserveAmount < amount (2-decimal safe) */
  reserveAmount?: number;
}
